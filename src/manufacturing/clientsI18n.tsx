function translateSpanishText(text: string) {
  const leadingWhitespace = text.match(/^\s*/)?.[0] ?? '';
  const trailingWhitespace = text.match(/\s*$/)?.[0] ?? '';
  const normalized = text.trim();
  const exact = spanish[normalized];
  if (exact) return `${leadingWhitespace}${exact}${trailingWhitespace}`;

  const translated = normalized
    .replace(/^(\d+) items · (\d+) total pieces$/, '$1 elementos · $2 piezas totales')
    .replace(/^(\d+) matching order$/, '$1 orden coincidente')
    .replace(/^(\d+) matching orders$/, '$1 órdenes coincidentes')
    .replace(/^Delete (.+)\?$/, '¿Eliminar $1?')
    .replace(/^(\d+) of (\d+)$/, '$1 de $2')
    .replace(/^(\d+) active reception vouchers$/, '$1 vales de recepción activos')
    .replace(/^(\d+) shown$/, '$1 mostrados');
  return translated === normalized ? text : `${leadingWhitespace}${translated}${trailingWhitespace}`;
}

export function translateClientsText(languageCode: ClientsLanguageCode, text: string) {
  return languageCode === 'es' ? translateSpanishText(text) : text;
}

const translatableProps = new Set(['aria-label', 'label', 'placeholder', 'title']);

export function localizeClientsTree(node: React.ReactNode, languageCode: ClientsLanguageCode): React.ReactNode {
  if (languageCode !== 'es') return node;
  if (typeof node === 'string') return translateSpanishText(node);
  if (Array.isArray(node)) return node.map((child) => localizeClientsTree(child, languageCode));
  if (!React.isValidElement(node)) return node;

  const element = node as React.ReactElement<Record<string, unknown>>;
  const nextProps: Record<string, unknown> = {};
  for (const propName of translatableProps) {
    const value = element.props[propName];
    if (typeof value === 'string') nextProps[propName] = translateSpanishText(value);
  }
  const options = element.props.options;
  if (Array.isArray(options)) {
    nextProps.options = options.map((option) => (
      option && typeof option === 'object' && typeof (option as { label?: unknown }).label === 'string'
        ? { ...option, label: translateSpanishText((option as { label: string }).label) }
        : option
    ));
  }
  if ('children' in element.props) {
    nextProps.children = React.Children.map(element.props.children as React.ReactNode, (child) => localizeClientsTree(child, languageCode));
  }
  return React.cloneElement(element, nextProps);
}
